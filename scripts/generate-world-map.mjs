// Generates components/world-map-data.ts from Natural Earth 110m country geometry.
// Projection: equirectangular, cropped to lat [-58, 84], lng [-180, 180].
// Usage: node scripts/generate-world-map.mjs [path/to/ne_110m_admin_0_countries.geojson]
import fs from "node:fs"
import path from "node:path"

const src =
  process.argv[2] ||
  path.join(process.env.TEMP || process.env.TMP || "/tmp", "ne_110m_countries.geojson")

const MAP_W = 1000
const LAT_TOP = 84
const LAT_BOTTOM = -58
const MAP_H = Math.round((MAP_W * (LAT_TOP - LAT_BOTTOM)) / 360)
const RDP_TOLERANCE = 0.22 // degrees
const MIN_RING_SPAN = 0.9 // drop rings smaller than this (tiny islands)

function project(lng, lat) {
  const x = ((lng + 180) / 360) * MAP_W
  const y = ((LAT_TOP - lat) / (LAT_TOP - LAT_BOTTOM)) * MAP_H
  return [x, y]
}

function simplify(points, tolerance) {
  if (points.length < 3) return points
  const sqTol = tolerance * tolerance
  const keep = new Array(points.length).fill(false)
  keep[0] = keep[points.length - 1] = true

  const stack = [[0, points.length - 1]]
  while (stack.length) {
    const [first, last] = stack.pop()
    let maxSqDist = 0
    let index = -1
    const [x1, y1] = points[first]
    const [x2, y2] = points[last]
    const dx = x2 - x1
    const dy = y2 - y1
    const lenSq = dx * dx + dy * dy
    for (let i = first + 1; i < last; i++) {
      const [px, py] = points[i]
      let t = lenSq === 0 ? 0 : ((px - x1) * dx + (py - y1) * dy) / lenSq
      t = Math.max(0, Math.min(1, t))
      const cx = x1 + t * dx
      const cy = y1 + t * dy
      const d = (px - cx) * (px - cx) + (py - cy) * (py - cy)
      if (d > maxSqDist) {
        maxSqDist = d
        index = i
      }
    }
    if (maxSqDist > sqTol && index !== -1) {
      keep[index] = true
      stack.push([first, index], [index, last])
    }
  }
  return points.filter((_, i) => keep[i])
}

function ringToPath(ring) {
  let d = ""
  ring.forEach(([x, y], i) => {
    const prev = i > 0 ? ring[i - 1] : null
    // Break the subpath where the ring jumps across the antimeridian
    const jump = prev && Math.abs(x - prev[0]) > MAP_W / 4
    d += `${i === 0 || jump ? "M" : "L"}${x.toFixed(1)} ${y.toFixed(1)}`
    if (jump) d += "Z"
  })
  return d + "Z"
}

const geo = JSON.parse(fs.readFileSync(src, "utf8"))
const countries = []

for (const feature of geo.features) {
  const name = feature.properties.NAME || feature.properties.ADMIN || "land"
  if (name === "Antarctica" || name === "Fr. S. Antarctic Lands") continue
  const geom = feature.geometry
  if (!geom) continue
  const polygons = geom.type === "Polygon" ? [geom.coordinates] : geom.coordinates

  const paths = []
  for (const polygon of polygons) {
    for (const ring of polygon) {
      const clamped = ring.map(([lng, lat]) => [
        Math.max(-180, Math.min(180, lng)),
        Math.max(LAT_BOTTOM, Math.min(LAT_TOP, lat)),
      ])
      const xs = clamped.map((p) => p[0])
      const ys = clamped.map((p) => p[1])
      const span = Math.max(Math.max(...xs) - Math.min(...xs), Math.max(...ys) - Math.min(...ys))
      if (span < MIN_RING_SPAN) continue

      let projected = clamped.map(([lng, lat]) => project(lng, lat))
      projected = simplify(projected, RDP_TOLERANCE)
      if (projected.length < 3) continue
      paths.push(ringToPath(projected))
    }
  }
  if (paths.length) countries.push({ name, d: paths.join("") })
}

const out = `// AUTO-GENERATED by scripts/generate-world-map.mjs from Natural Earth 110m data.
// Equirectangular projection, lng [-180, 180], lat [${LAT_BOTTOM}, ${LAT_TOP}].
export const WORLD_MAP_W = ${MAP_W}
export const WORLD_MAP_H = ${MAP_H}
export const MAP_LAT_TOP = ${LAT_TOP}
export const MAP_LAT_BOTTOM = ${LAT_BOTTOM}

export const latToY = (lat: number) =>
  ((${LAT_TOP} - lat) / (${LAT_TOP} - ${LAT_BOTTOM})) * WORLD_MAP_H

export const lngToX = (lng: number) => ((lng + 180) / 360) * WORLD_MAP_W

export const WORLD_COUNTRIES: { name: string; d: string }[] = ${JSON.stringify(countries)}
`

const dest = path.resolve("components/world-map-data.ts")
fs.writeFileSync(dest, out, "utf8")
const bytes = fs.statSync(dest).size
console.log(`wrote ${dest}: ${countries.length} countries, ${bytes} bytes, ${MAP_W}x${MAP_H}`)



